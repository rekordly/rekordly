var (
	ErrCannotEditNonDraftEstimate = errors.New("cannot edit an estimate that is not in draft status")
	ErrEstimateAlreadyConverted   = errors.New("estimate is already converted to an invoice")
	ErrEstimateInvalidStatus      = errors.New("invalid estimate status")
	ErrNoEstimateItems            = errors.New("estimate must have at least one line item")
)

type EstimateItemInput struct {
	Description    string `json:"description" binding:"required"`
	Quantity       string `json:"quantity"` // decimal string e.g. "2" or "1.5"
	UnitPriceMinor int64  `json:"unit_price_minor"`
	UnitPrice      string `json:"unit_price"` // optional major decimal string
}

type CreateEstimateInput struct {
	CustomerID     int64               `json:"customer_id"` // optional
	CustomerName   string              `json:"customer_name" binding:"required"`
	EstimateNumber string              `json:"estimate_number"`               // optional, autogenerated if empty
	IssueDate      string              `json:"issue_date" binding:"required"` // YYYY-MM-DD
	ExpiryDate     string              `json:"expiry_date" binding:"required"`
	TaxAmountMinor int64               `json:"tax_amount_minor"`
	TaxAmount      string              `json:"tax_amount"` // optional major decimal string
	Currency       string              `json:"currency"`
	Status         string              `json:"status"` // draft, sent, accepted (default draft)
	Items          []EstimateItemInput `json:"items" binding:"required"`
	Notes          string              `json:"notes"`
	Terms          string              `json:"terms"`
	IdempotencyKey string              `json:"idempotency_key"`
}

type UpdateDraftEstimateInput struct {
	CustomerID     int64               `json:"customer_id"`
	CustomerName   string              `json:"customer_name"`
	IssueDate      string              `json:"issue_date"`
	ExpiryDate     string              `json:"expiry_date"`
	TaxAmountMinor int64               `json:"tax_amount_minor"`
	TaxAmount      string              `json:"tax_amount"`
	Items          []EstimateItemInput `json:"items"`
	Notes          string              `json:"notes"`
	Terms          string              `json:"terms"`
}

type EstimateDetail struct {
	Estimate db.Estimate        `json:"estimate"`
	Items    []db.EstimateItem  `json:"items"`
}

func (s *Service) CreateEstimate(ctx context.Context, workspaceID, userID int64, in CreateEstimateInput) (EstimateDetail, error) {
	idempKey := strings.TrimSpace(in.IdempotencyKey)
	if idempKey != "" {
		existing, err := s.queries.GetEstimateByIdempotency(ctx, db.GetEstimateByIdempotencyParams{
			WorkspaceID:    workspaceID,
			IdempotencyKey: pgtype.Text{String: idempKey, Valid: true},
		})
		if err == nil {
			return s.GetEstimate(ctx, workspaceID, existing.ID)
		} else if !errors.Is(err, pgx.ErrNoRows) {
			return EstimateDetail{}, err
		}
	}

	if len(in.Items) == 0 {
		return EstimateDetail{}, ErrNoEstimateItems
	}

	currency := strings.ToUpper(strings.TrimSpace(in.Currency))
	if currency == "" {
		currency = "NGN"
	}
	exponent := CurrencyExponent(currency)

	var custID pgtype.Int8
	custName := strings.TrimSpace(in.CustomerName)
	if in.CustomerID > 0 {
		party, err := s.queries.GetCounterpartyByID(ctx, db.GetCounterpartyByIDParams{
			ID:          in.CustomerID,
			WorkspaceID: workspaceID,
		})
		if err != nil {
			return EstimateDetail{}, ErrForbiddenParty
		}
		custID = pgtype.Int8{Int64: in.CustomerID, Valid: true}
		if custName == "" {
			custName = party.Name
		}
	}
	if custName == "" {
		custName = "Prospective Customer"
	}

	issDate, err := time.Parse("2006-01-02", in.IssueDate)
	if err != nil {
		return EstimateDetail{}, fmt.Errorf("invalid issue_date: %w", err)
	}
	expDate, err := time.Parse("2006-01-02", in.ExpiryDate)
	if err != nil {
		return EstimateDetail{}, fmt.Errorf("invalid expiry_date: %w", err)
	}

	estNumber := strings.TrimSpace(in.EstimateNumber)
	if estNumber == "" {
		count, _ := s.countEstimates(ctx, workspaceID)
		estNumber = fmt.Sprintf("EST-%04d", count+1)
	}

	status := strings.ToLower(strings.TrimSpace(in.Status))
	if status == "" {
		status = "draft"
	}

	type lineCalc struct {
		description string
		quantity    decimal.Decimal
		unitPrice   int64
		amount      int64
	}

	var lines []lineCalc
	var subtotal int64

	for _, it := range in.Items {
		desc := strings.TrimSpace(it.Description)
		if desc == "" {
			return EstimateDetail{}, errors.New("item description cannot be empty")
		}

		qtyStr := strings.TrimSpace(it.Quantity)
		if qtyStr == "" {
			qtyStr = "1"
		}
		qty, err := decimal.NewFromString(qtyStr)
		if err != nil || qty.LessThanOrEqual(decimal.Zero) {
			return EstimateDetail{}, errors.New("item quantity must be greater than zero")
		}

		unitPrice := it.UnitPriceMinor
		if unitPrice == 0 && it.UnitPrice != "" {
			parsed, err := ParseMajorToMinor(it.UnitPrice, exponent)
			if err != nil {
				return EstimateDetail{}, fmt.Errorf("invalid unit_price: %w", err)
			}
			unitPrice = parsed
		}
		if unitPrice < 0 {
			return EstimateDetail{}, errors.New("item unit price cannot be negative")
		}

		lineAmount := qty.Mul(decimal.NewFromInt(unitPrice)).Round(0).IntPart()
		subtotal += lineAmount

		lines = append(lines, lineCalc{
			description: desc,
			quantity:    qty,
			unitPrice:   unitPrice,
			amount:      lineAmount,
		})
	}

	tax := in.TaxAmountMinor
	if tax == 0 && in.TaxAmount != "" {
		parsed, err := ParseMajorToMinor(in.TaxAmount, exponent)
		if err != nil {
			return EstimateDetail{}, fmt.Errorf("invalid tax_amount: %w", err)
		}
		tax = parsed
	}
	if tax < 0 {
		return EstimateDetail{}, errors.New("tax cannot be negative")
	}

	total := subtotal + tax

	tx, err := s.pool.Begin(ctx)
	if err != nil {
		return EstimateDetail{}, err
	}
	defer tx.Rollback(ctx)
	qtx := s.queries.WithTx(tx)

	est, err := qtx.CreateEstimate(ctx, db.CreateEstimateParams{
		WorkspaceID:      workspaceID,
		EstimateNumber:   estNumber,
		CustomerID:       custID,
		CustomerName:     custName,
		IssueDate:        pgtype.Date{Time: issDate, Valid: true},
		ExpiryDate:       pgtype.Date{Time: expDate, Valid: true},
		Currency:         currency,
		CurrencyExponent: int32(exponent),
		SubtotalMinor:    subtotal,
		TaxAmountMinor:   tax,
		TotalAmountMinor: total,
		Status:           status,
		Notes:            pgtype.Text{String: in.Notes, Valid: in.Notes != ""},
		Terms:            pgtype.Text{String: in.Terms, Valid: in.Terms != ""},
		IdempotencyKey:   pgtype.Text{String: idempKey, Valid: idempKey != ""},
		CreatedByUserID:  pgtype.Int8{Int64: userID, Valid: userID > 0},
	})
	if err != nil {
		return EstimateDetail{}, fmt.Errorf("failed to insert estimate: %w", err)
	}

	var insertedItems []db.EstimateItem
	for _, l := range lines {
		item, err := qtx.CreateEstimateItem(ctx, db.CreateEstimateItemParams{
			EstimateID:     est.ID,
			WorkspaceID:    workspaceID,
			Description:    l.description,
			Quantity:       l.quantity,
			UnitPriceMinor: l.unitPrice,
			AmountMinor:    l.amount,
		})
		if err != nil {
			return EstimateDetail{}, fmt.Errorf("failed to insert estimate item: %w", err)
		}
		insertedItems = append(insertedItems, item)
	}

	if err := tx.Commit(ctx); err != nil {
		return EstimateDetail{}, err
	}

	return EstimateDetail{
		Estimate: est,
		Items:    insertedItems,
	}, nil
}

func (s *Service) GetEstimate(ctx context.Context, workspaceID, estimateID int64) (EstimateDetail, error) {
	est, err := s.queries.GetEstimateByID(ctx, db.GetEstimateByIDParams{
		ID:          estimateID,
		WorkspaceID: workspaceID,
	})
	if err != nil {
		return EstimateDetail{}, err
	}

	items, err := s.queries.ListEstimateItems(ctx, db.ListEstimateItemsParams{
		EstimateID:  estimateID,
		WorkspaceID: workspaceID,
	})
	if err != nil {
		return EstimateDetail{}, err
	}

	return EstimateDetail{
		Estimate: est,
		Items:    items,
	}, nil
}

func (s *Service) ListEstimates(ctx context.Context, workspaceID int64, params db.ListEstimatesParams) ([]db.Estimate, error) {
	params.WorkspaceID = workspaceID
	if params.Limit <= 0 {
		params.Limit = 50
	}
	return s.queries.ListEstimates(ctx, params)
}

func (s *Service) UpdateEstimateStatus(ctx context.Context, workspaceID, estimateID int64, status string) (EstimateDetail, error) {
	status = strings.ToLower(strings.TrimSpace(status))
	validStatuses := map[string]bool{"draft": true, "sent": true, "accepted": true, "declined": true, "expired": true}
	if !validStatuses[status] {
		return EstimateDetail{}, ErrEstimateInvalidStatus
	}

	est, err := s.queries.UpdateEstimateStatus(ctx, db.UpdateEstimateStatusParams{
		ID:          estimateID,
		WorkspaceID: workspaceID,
		Status:      status,
	})
	if err != nil {
		return EstimateDetail{}, err
	}

	items, err := s.queries.ListEstimateItems(ctx, db.ListEstimateItemsParams{
		EstimateID:  estimateID,
		WorkspaceID: workspaceID,
	})
	if err != nil {
		return EstimateDetail{}, err
	}

	return EstimateDetail{
		Estimate: est,
		Items:    items,
	}, nil
}

func (s *Service) ConvertEstimateToInvoice(ctx context.Context, workspaceID, userID, estimateID int64, idempotencyKey string) (InvoiceDetail, error) {
	estDetail, err := s.GetEstimate(ctx, workspaceID, estimateID)
	if err != nil {
		return InvoiceDetail{}, err
	}

	est := estDetail.Estimate
	if est.Status == "converted" {
		return InvoiceDetail{}, ErrEstimateAlreadyConverted
	}

	// Prepare invoice items
	var invoiceItems []InvoiceItemInput
	for _, it := range estDetail.Items {
		qtyInt := int32(it.Quantity.Round(0).IntPart())
		if qtyInt < 1 {
			qtyInt = 1
		}
		invoiceItems = append(invoiceItems, InvoiceItemInput{
			Description:    it.Description,
			Quantity:       qtyInt,
			UnitPriceMinor: it.UnitPriceMinor,
		})
	}

	// Customer ID
	custID := int64(0)
	if est.CustomerID.Valid {
		custID = est.CustomerID.Int64
	} else {
		// Create or find counterparty for customer_name
		cp, err := s.queries.CreateCounterparty(ctx, db.CreateCounterpartyParams{
			WorkspaceID: workspaceID,
			Name:        est.CustomerName,
			PartyType:   "customer",
			IsActive:    true,
		})
		if err == nil {
			custID = cp.ID
		}
	}

	todayStr := time.Now().Format("2006-01-02")
	dueStr := time.Now().AddDate(0, 0, 14).Format("2006-01-02")

	invoiceIn := CreateInvoiceInput{
		CustomerID:     custID,
		CustomerName:   est.CustomerName,
		IssueDate:      todayStr,
		DueDate:        dueStr,
		TaxAmountMinor: est.TaxAmountMinor,
		Currency:       est.Currency,
		Status:         "draft",
		Items:          invoiceItems,
		Notes:          est.Notes.String,
		Terms:          est.Terms.String,
		IdempotencyKey: idempotencyKey,
	}

	invDetail, err := s.CreateInvoice(ctx, workspaceID, userID, invoiceIn)
	if err != nil {
		return InvoiceDetail{}, fmt.Errorf("failed to create invoice from estimate: %w", err)
	}

	// Mark estimate as converted
	_, err = s.queries.MarkEstimateConverted(ctx, db.MarkEstimateConvertedParams{
		ID:                 estimateID,
		WorkspaceID:        workspaceID,
		ConvertedInvoiceID: pgtype.Int8{Int64: invDetail.Invoice.ID, Valid: true},
	})
	if err != nil {
		return InvoiceDetail{}, fmt.Errorf("failed to update estimate converted status: %w", err)
	}

	return invDetail, nil
}

func (s *Service) countEstimates(ctx context.Context, workspaceID int64) (int64, error) {
	var count int64
	err := s.pool.QueryRow(ctx, `SELECT count(*) FROM estimates WHERE workspace_id = $1`, workspaceID).Scan(&count)
	return count, err
}
