// ---------------- Customer Deposits and Wallets ----------------

type CustomerWalletDepositInput struct {
	AmountMinor    int64  `json:"amount_minor"`
	AmountMajor    string `json:"amount"` // optional
	Currency       string `json:"currency"`
	MoneyAccountID int64  `json:"money_account_id" binding:"required"`
	Notes          string `json:"notes"`
	Reference      string `json:"reference"`
	IdempotencyKey string `json:"idempotency_key"`
}

type WalletDepositResult struct {
	Wallet      db.CustomerWallet    `json:"wallet"`
	Transaction db.WalletTransaction `json:"transaction"`
	Ledger      *db.LedgerEntry      `json:"ledger_entry,omitempty"`
}

func (s *Service) DepositToCustomerWallet(ctx context.Context, workspaceID, userID, customerID int64, in CustomerWalletDepositInput) (WalletDepositResult, error) {
	party, err := s.queries.GetCounterpartyByID(ctx, db.GetCounterpartyByIDParams{
		ID:          customerID,
		WorkspaceID: workspaceID,
	})
	if err != nil {
		return WalletDepositResult{}, ErrForbiddenParty
	}

	currency := strings.ToUpper(strings.TrimSpace(in.Currency))
	if currency == "" {
		currency = "NGN"
	}
	exponent := CurrencyExponent(currency)

	amountMinor := in.AmountMinor
	if in.AmountMajor != "" {
		parsed, err := ParseMajorToMinor(in.AmountMajor, exponent)
		if err != nil {
			return WalletDepositResult{}, err
		}
		amountMinor = parsed
	}
	if amountMinor <= 0 {
		return WalletDepositResult{}, ErrNegativeAmount
	}

	acc, err := s.queries.GetMoneyAccountByID(ctx, db.GetMoneyAccountByIDParams{
		ID:          in.MoneyAccountID,
		WorkspaceID: workspaceID,
	})
	if err != nil {
		return WalletDepositResult{}, ErrForbiddenAccount
	}

	tx, err := s.pool.Begin(ctx)
	if err != nil {
		return WalletDepositResult{}, err
	}
	defer func() { _ = tx.Rollback(ctx) }()

	qtx := s.queries.WithTx(tx)

	// Ensure wallet row exists
	if _, err := qtx.GetOrCreateCustomerWallet(ctx, db.GetOrCreateCustomerWalletParams{
		WorkspaceID:      workspaceID,
		CustomerID:       customerID,
		Currency:         currency,
		CurrencyExponent: int32(exponent),
	}); err != nil {
		return WalletDepositResult{}, fmt.Errorf("get or create wallet: %w", err)
	}

	// Update wallet balance (+ amount)
	updatedWallet, err := qtx.UpdateCustomerWalletBalance(ctx, db.UpdateCustomerWalletBalanceParams{
		WorkspaceID:  workspaceID,
		CustomerID:   customerID,
		Currency:     currency,
		BalanceMinor: amountMinor,
	})
	if err != nil {
		return WalletDepositResult{}, fmt.Errorf("update wallet balance: %w", err)
	}

	// Update money account balance (+ amount)
	_, err = qtx.UpdateMoneyAccountBalance(ctx, db.UpdateMoneyAccountBalanceParams{
		ID:                  acc.ID,
		WorkspaceID:         workspaceID,
		CurrentBalanceMinor: amountMinor,
	})
	if err != nil {
		return WalletDepositResult{}, fmt.Errorf("update money account balance: %w", err)
	}

	var idempParam pgtype.Text
	if strings.TrimSpace(in.IdempotencyKey) != "" {
		idempParam = pgtype.Text{String: strings.TrimSpace(in.IdempotencyKey), Valid: true}
	}

	// Record wallet transaction
	wTxn, err := qtx.CreateWalletTransaction(ctx, db.CreateWalletTransactionParams{
		WorkspaceID:       workspaceID,
		CustomerID:        customerID,
		TransactionType:   "deposit",
		AmountMinor:       amountMinor,
		BalanceAfterMinor: updatedWallet.BalanceMinor,
		MoneyAccountID:    pgtype.Int8{Int64: acc.ID, Valid: true},
		InvoiceID:         pgtype.Int8{Valid: false},
		Notes:             optionalPgText(in.Notes),
		Reference:         optionalPgText(in.Reference),
		IdempotencyKey:    idempParam,
		CreatedByUserID:   pgtype.Int8{Int64: userID, Valid: true},
	})
	if err != nil {
		return WalletDepositResult{}, fmt.Errorf("record wallet transaction: %w", err)
	}

	// Create balanced double-entry ledger entry:
	// Debit: Bank / Cash (Asset)
	// Credit: Customer Deposit Liability (Liability)
	entry, err := qtx.CreateLedgerEntry(ctx, db.CreateLedgerEntryParams{
		WorkspaceID:      workspaceID,
		SourceType:       "deposit",
		SourceID:         wTxn.ID,
		EntryDate:        pgtype.Date{Time: time.Now().UTC(), Valid: true},
		Currency:         currency,
		CurrencyExponent: int32(exponent),
		Description:      pgtype.Text{String: "Customer deposit from " + party.Name, Valid: true},
	})
	if err != nil {
		return WalletDepositResult{}, err
	}

	_, err = qtx.CreateLedgerLine(ctx, db.CreateLedgerLineParams{
		LedgerEntryID: entry.ID,
		WorkspaceID:   workspaceID,
		AccountID:     pgtype.Int8{Int64: acc.ID, Valid: true},
		AccountClass:  "asset",
		DebitMinor:    amountMinor,
		CreditMinor:   0,
		Description:   pgtype.Text{String: "Deposit into " + acc.Name, Valid: true},
	})
	if err != nil {
		return WalletDepositResult{}, err
	}

	_, err = qtx.CreateLedgerLine(ctx, db.CreateLedgerLineParams{
		LedgerEntryID: entry.ID,
		WorkspaceID:   workspaceID,
		AccountID:     pgtype.Int8{Valid: false},
		AccountClass:  "liability",
		DebitMinor:    0,
		CreditMinor:   amountMinor,
		Description:   pgtype.Text{String: "Customer Deposit Liability: " + party.Name, Valid: true},
	})
	if err != nil {
		return WalletDepositResult{}, err
	}

	if err := tx.Commit(ctx); err != nil {
		return WalletDepositResult{}, err
	}

	return WalletDepositResult{
		Wallet:      updatedWallet,
		Transaction: wTxn,
		Ledger:      &entry,
	}, nil
}

