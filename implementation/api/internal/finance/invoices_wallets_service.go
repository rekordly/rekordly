// PayInvoiceWithWallet pays an outstanding invoice using available customer wallet balance.
// Prohibits negative wallet balances and over-allocation.
func (s *Service) PayInvoiceWithWallet(ctx context.Context, workspaceID, userID, invoiceID int64, amountMinor int64) (InvoiceDetail, error) {
	if amountMinor <= 0 {
		return InvoiceDetail{}, ErrNegativeAmount
	}

	tx, err := s.pool.Begin(ctx)
	if err != nil {
		return InvoiceDetail{}, err
	}
	defer func() { _ = tx.Rollback(ctx) }()

	qtx := s.queries.WithTx(tx)

	inv, err := qtx.GetInvoiceByID(ctx, db.GetInvoiceByIDParams{
		ID:          invoiceID,
		WorkspaceID: workspaceID,
	})
	if errors.Is(err, pgx.ErrNoRows) {
		return InvoiceDetail{}, ErrNotFound
	} else if err != nil {
		return InvoiceDetail{}, err
	}

	if inv.Status == "draft" {
		return InvoiceDetail{}, errors.New("invoice must be finalized before applying wallet payment")
	}
	if inv.Status == "voided" {
		return InvoiceDetail{}, errors.New("cannot pay a voided invoice")
	}

	// OVER-ALLOCATION PROTECTION
	outstanding := inv.TotalAmountMinor - inv.PaidAmountMinor
	if outstanding <= 0 {
		return InvoiceDetail{}, ErrAlreadyFullyPaid
	}
	if amountMinor > outstanding {
		return InvoiceDetail{}, fmt.Errorf("%w: payment %d exceeds invoice outstanding %d", ErrOverpayment, amountMinor, outstanding)
	}

	// Check customer wallet balance: NO NEGATIVE WALLET PROHIBITION
	wallet, err := qtx.GetCustomerWallet(ctx, db.GetCustomerWalletParams{
		WorkspaceID: workspaceID,
		CustomerID:  inv.CustomerID,
		Currency:    inv.Currency,
	})
	if errors.Is(err, pgx.ErrNoRows) || wallet.BalanceMinor < amountMinor {
		return InvoiceDetail{}, ErrInsufficientWalletBalance
	}

	// 1. Deduct wallet balance
	updatedWallet, err := qtx.UpdateCustomerWalletBalance(ctx, db.UpdateCustomerWalletBalanceParams{
		WorkspaceID:  workspaceID,
		CustomerID:   inv.CustomerID,
		Currency:     inv.Currency,
		BalanceMinor: -amountMinor,
	})
	if err != nil {
		return InvoiceDetail{}, fmt.Errorf("deduct wallet balance: %w", err)
	}

	// 2. Record wallet transaction
	wTxn, err := qtx.CreateWalletTransaction(ctx, db.CreateWalletTransactionParams{
		WorkspaceID:       workspaceID,
		CustomerID:        inv.CustomerID,
		TransactionType:   "invoice_payment",
		AmountMinor:       amountMinor,
		BalanceAfterMinor: updatedWallet.BalanceMinor,
		MoneyAccountID:    pgtype.Int8{Valid: false},
		InvoiceID:         pgtype.Int8{Int64: inv.ID, Valid: true},
		Notes:             pgtype.Text{String: "Payment applied to invoice #" + inv.InvoiceNumber, Valid: true},
		CreatedByUserID:   pgtype.Int8{Int64: userID, Valid: true},
	})
	if err != nil {
		return InvoiceDetail{}, fmt.Errorf("record wallet invoice payment: %w", err)
	}

	// 3. Update invoice paid amount
	updatedInvoice, err := qtx.UpdateInvoicePaidAmount(ctx, db.UpdateInvoicePaidAmountParams{
		ID:              inv.ID,
		WorkspaceID:     workspaceID,
		PaidAmountMinor: amountMinor,
	})
	if err != nil {
		return InvoiceDetail{}, fmt.Errorf("update invoice paid amount: %w", err)
	}

	// 4. Create balanced double-entry ledger entry:
	// Debit: Customer Deposit Liability (Liability)
	// Credit: Accounts Receivable (Asset)
	entry, err := qtx.CreateLedgerEntry(ctx, db.CreateLedgerEntryParams{
		WorkspaceID:      workspaceID,
		SourceType:       "wallet_payment",
		SourceID:         wTxn.ID,
		EntryDate:        pgtype.Date{Time: time.Now().UTC(), Valid: true},
		Currency:         inv.Currency,
		CurrencyExponent: inv.CurrencyExponent,
		Description:      pgtype.Text{String: "Wallet deposit application to invoice #" + inv.InvoiceNumber, Valid: true},
	})
	if err != nil {
		return InvoiceDetail{}, err
	}

	_, err = qtx.CreateLedgerLine(ctx, db.CreateLedgerLineParams{
		LedgerEntryID: entry.ID,
		WorkspaceID:   workspaceID,
		AccountID:     pgtype.Int8{Valid: false},
		AccountClass:  "liability",
		DebitMinor:    amountMinor,
		CreditMinor:   0,
		Description:   pgtype.Text{String: "Reduction in Customer Deposit Liability", Valid: true},
	})
	if err != nil {
		return InvoiceDetail{}, err
	}

	_, err = qtx.CreateLedgerLine(ctx, db.CreateLedgerLineParams{
		LedgerEntryID: entry.ID,
		WorkspaceID:   workspaceID,
		AccountID:     pgtype.Int8{Valid: false},
		AccountClass:  "asset",
		DebitMinor:    0,
		CreditMinor:   amountMinor,
		Description:   pgtype.Text{String: "Settlement of Accounts Receivable", Valid: true},
	})
	if err != nil {
		return InvoiceDetail{}, err
	}

	items, err := qtx.ListInvoiceItemsByInvoiceID(ctx, db.ListInvoiceItemsByInvoiceIDParams{
		InvoiceID:   inv.ID,
		WorkspaceID: workspaceID,
	})
	if err != nil {
		return InvoiceDetail{}, err
	}

	if err := tx.Commit(ctx); err != nil {
		return InvoiceDetail{}, err
	}

	return InvoiceDetail{
		Invoice: updatedInvoice,
		Items:   items,
	}, nil
}
