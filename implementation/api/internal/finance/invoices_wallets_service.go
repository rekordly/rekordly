var (
	ErrCannotEditFinalizedInvoice = errors.New("cannot edit an invoice that is already finalized")
	ErrAlreadyFinalized           = errors.New("invoice is already finalized")
	ErrCannotFinalizeVoided       = errors.New("cannot finalize a voided invoice")
	ErrInsufficientWalletBalance  = errors.New("insufficient customer wallet balance: negative balance prohibited")
	ErrNoInvoiceItems             = errors.New("invoice must have at least one line item")
	ErrCannotVoidPaidInvoice      = errors.New("cannot void an invoice with active payments; void payments first")
	ErrInvoiceAlreadyVoided       = errors.New("invoice is already voided")
)

type InvoiceItemInput struct {
	Description    string `json:"description" binding:"required"`
	Quantity       int32  `json:"quantity" binding:"required"`
	UnitPriceMinor int64  `json:"unit_price_minor"`
	UnitPrice      string `json:"unit_price"` // optional major string
	DiscountMinor  int64  `json:"discount_minor"`
}

type CreateInvoiceInput struct {
	CustomerID        int64              `json:"customer_id" binding:"required"`
	CustomerName      string             `json:"customer_name"`
	InvoiceNumber     string             `json:"invoice_number"`                // optional, autogenerated if empty
	IssueDate         string             `json:"issue_date" binding:"required"` // YYYY-MM-DD
	DueDate           string             `json:"due_date" binding:"required"`   // YYYY-MM-DD
	TaxAmountMinor    int64              `json:"tax_amount_minor"`
	TaxAmount         string             `json:"tax_amount"` // optional major decimal string
	DiscountMinor     int64              `json:"discount_minor"`
	DiscountAmount    string             `json:"discount_amount"`
	DeliveryFeeMinor  int64              `json:"delivery_fee_minor"`
	DeliveryFeeAmount string             `json:"delivery_fee_amount"`
	Currency          string             `json:"currency"`
	Status            string             `json:"status"` // draft or finalized (default draft)
	Items             []InvoiceItemInput `json:"items" binding:"required"`
	Notes             string             `json:"notes"`
	Terms             string             `json:"terms"`
	IdempotencyKey    string             `json:"idempotency_key"`
}

type UpdateDraftInvoiceInput struct {
	CustomerID     int64              `json:"customer_id"`
	CustomerName   string             `json:"customer_name"`
	IssueDate      string             `json:"issue_date"`
	DueDate        string             `json:"due_date"`
	TaxAmountMinor int64              `json:"tax_amount_minor"`
	Items          []InvoiceItemInput `json:"items"`
	Notes          string             `json:"notes"`
	Terms          string             `json:"terms"`
}

type InvoiceDetail struct {
	Invoice  db.Invoice       `json:"invoice"`
	Items    []db.InvoiceItem `json:"items"`
	Payments []PaymentDetail  `json:"payments,omitempty"`
}

func (s *Service) CreateInvoice(ctx context.Context, workspaceID, userID int64, in CreateInvoiceInput) (InvoiceDetail, error) {
	idempKey := strings.TrimSpace(in.IdempotencyKey)
	if idempKey != "" {
		existing, err := s.queries.GetInvoiceByIdempotency(ctx, db.GetInvoiceByIdempotencyParams{
			WorkspaceID:    workspaceID,
			IdempotencyKey: pgtype.Text{String: idempKey, Valid: true},
		})
		if err == nil {
			return s.GetInvoice(ctx, workspaceID, existing.ID)
		} else if !errors.Is(err, pgx.ErrNoRows) {
			return InvoiceDetail{}, err
		}
	}

	if len(in.Items) == 0 {
		return InvoiceDetail{}, ErrNoInvoiceItems
	}

	currency := strings.ToUpper(strings.TrimSpace(in.Currency))
	if currency == "" {
		currency = "NGN"
	}
	exponent := CurrencyExponent(currency)

	// Validate customer
	party, err := s.queries.GetCounterpartyByID(ctx, db.GetCounterpartyByIDParams{
		ID:          in.CustomerID,
		WorkspaceID: workspaceID,
	})
	if err != nil {
		return InvoiceDetail{}, ErrForbiddenParty
	}
	custName := strings.TrimSpace(in.CustomerName)
	if custName == "" {
		custName = party.Name
	}

	issueDate, err := time.Parse("2006-01-02", strings.TrimSpace(in.IssueDate))
	if err != nil {
		return InvoiceDetail{}, fmt.Errorf("invalid issue date: %w", err)
	}
	dueDate, err := time.Parse("2006-01-02", strings.TrimSpace(in.DueDate))
	if err != nil {
		return InvoiceDetail{}, fmt.Errorf("invalid due date: %w", err)
	}

	// Compute item amounts and subtotal strictly using integer arithmetic
	var subtotalMinor int64
	type computedItem struct {
		desc        string
		qty         int32
		unitPrice   int64
		amountMinor int64
	}
	var computedItems []computedItem

	for _, item := range in.Items {
		desc := strings.TrimSpace(item.Description)
		if desc == "" {
			return InvoiceDetail{}, errors.New("item description is required")
		}
		if item.Quantity <= 0 {
			return InvoiceDetail{}, errors.New("item quantity must be greater than zero")
		}

		unitPrice := item.UnitPriceMinor
		if item.UnitPrice != "" {
			parsed, err := ParseMajorToMinor(item.UnitPrice, exponent)
			if err != nil {
				return InvoiceDetail{}, err
			}
			unitPrice = parsed
		}
		if unitPrice < 0 {
			return InvoiceDetail{}, errors.New("unit price cannot be negative")
		}

		lineAmount := int64(item.Quantity) * unitPrice
		subtotalMinor += lineAmount

		computedItems = append(computedItems, computedItem{
			desc:        desc,
			qty:         item.Quantity,
			unitPrice:   unitPrice,
			amountMinor: lineAmount,
		})
	}

	if in.TaxAmount != "" {
		parsed, err := ParseMajorToMinor(in.TaxAmount, CurrencyExponent(in.Currency))
		if err != nil {
			return InvoiceDetail{}, err
		}
		in.TaxAmountMinor = parsed
	}
	if in.DiscountAmount != "" {
		parsed, err := ParseMajorToMinor(in.DiscountAmount, CurrencyExponent(in.Currency))
		if err != nil {
			return InvoiceDetail{}, err
		}
		in.DiscountMinor = parsed
	}
	if in.DeliveryFeeAmount != "" {
		parsed, err := ParseMajorToMinor(in.DeliveryFeeAmount, CurrencyExponent(in.Currency))
		if err != nil {
			return InvoiceDetail{}, err
		}
		in.DeliveryFeeMinor = parsed
	}
	if in.DiscountMinor < 0 || in.DeliveryFeeMinor < 0 {
		return InvoiceDetail{}, errors.New("discount and delivery fee cannot be negative")
	}

	totalMinor := subtotalMinor - in.DiscountMinor + in.TaxAmountMinor + in.DeliveryFeeMinor
	if totalMinor < 0 {
		totalMinor = 0
	}

	status := strings.ToLower(strings.TrimSpace(in.Status))
	if status == "" {
		status = "draft"
	}
	if status != "draft" && status != "finalized" {
		return InvoiceDetail{}, errors.New("initial invoice status must be draft or finalized")
	}

	invNum := strings.TrimSpace(in.InvoiceNumber)
	if invNum == "" {
		invNum = fmt.Sprintf("INV-%d", time.Now().UnixNano()%1000000)
	}

	tx, err := s.pool.Begin(ctx)
	if err != nil {
		return InvoiceDetail{}, err
	}
	defer func() { _ = tx.Rollback(ctx) }()

	qtx := s.queries.WithTx(tx)

	var idempParam pgtype.Text
	if idempKey != "" {
		idempParam = pgtype.Text{String: idempKey, Valid: true}
	}

	invRecord, err := qtx.CreateInvoice(ctx, db.CreateInvoiceParams{
		WorkspaceID:      workspaceID,
		CustomerID:       party.ID,
		CustomerName:     custName,
		InvoiceNumber:    invNum,
		IssueDate:        pgtype.Date{Time: issueDate, Valid: true},
		DueDate:          pgtype.Date{Time: dueDate, Valid: true},
		SubtotalMinor:    subtotalMinor,
		TaxAmountMinor:   in.TaxAmountMinor,
		TotalAmountMinor: totalMinor,
		PaidAmountMinor:  0,
		Currency:         currency,
		CurrencyExponent: int32(exponent),
		Status:           status,
		Notes:            optionalPgText(in.Notes),
		Terms:            optionalPgText(in.Terms),
		IdempotencyKey:   idempParam,
		CreatedByUserID:  pgtype.Int8{Int64: userID, Valid: true},
	})
	if err != nil {
		return InvoiceDetail{}, fmt.Errorf("create invoice: %w", err)
	}
	if in.DiscountMinor > 0 || in.DeliveryFeeMinor > 0 {
		updatedInv, chErr := qtx.SetInvoiceCharges(ctx, db.SetInvoiceChargesParams{
			ID:               invRecord.ID,
			WorkspaceID:      workspaceID,
			DiscountMinor:    in.DiscountMinor,
			DeliveryFeeMinor: in.DeliveryFeeMinor,
			TotalAmountMinor: totalMinor,
		})
		if chErr != nil {
			return InvoiceDetail{}, fmt.Errorf("set invoice charges: %w", chErr)
		}
		invRecord = updatedInv
	}

	var savedItems []db.InvoiceItem
	for _, it := range computedItems {
		itemRec, err := qtx.CreateInvoiceItem(ctx, db.CreateInvoiceItemParams{
			InvoiceID:      invRecord.ID,
			WorkspaceID:    workspaceID,
			Description:    it.desc,
			Quantity:       it.qty,
			UnitPriceMinor: it.unitPrice,
			AmountMinor:    it.amountMinor,
		})
		if err != nil {
			return InvoiceDetail{}, fmt.Errorf("create invoice item: %w", err)
		}
		savedItems = append(savedItems, itemRec)
	}

	// If finalized immediately, post double-entry ledger entries!
	if status == "finalized" {
		if err := s.postInvoiceLedger(ctx, qtx, workspaceID, invRecord); err != nil {
			return InvoiceDetail{}, err
		}
	}

	if err := tx.Commit(ctx); err != nil {
		return InvoiceDetail{}, fmt.Errorf("commit invoice: %w", err)
	}

	return InvoiceDetail{
		Invoice: invRecord,
		Items:   savedItems,
	}, nil
}

func (s *Service) UpdateDraftInvoice(ctx context.Context, workspaceID, userID, invoiceID int64, in UpdateDraftInvoiceInput) (InvoiceDetail, error) {
	orig, err := s.queries.GetInvoiceByID(ctx, db.GetInvoiceByIDParams{
		ID:          invoiceID,
		WorkspaceID: workspaceID,
	})
	if errors.Is(err, pgx.ErrNoRows) {
		return InvoiceDetail{}, ErrNotFound
	} else if err != nil {
		return InvoiceDetail{}, err
	}

	if orig.Status != "draft" {
		return InvoiceDetail{}, ErrCannotEditFinalizedInvoice
	}

	tx, err := s.pool.Begin(ctx)
	if err != nil {
		return InvoiceDetail{}, err
	}
	defer func() { _ = tx.Rollback(ctx) }()

	qtx := s.queries.WithTx(tx)

	custID := orig.CustomerID
	custName := orig.CustomerName
	if in.CustomerID > 0 {
		party, err := qtx.GetCounterpartyByID(ctx, db.GetCounterpartyByIDParams{
			ID:          in.CustomerID,
			WorkspaceID: workspaceID,
		})
		if err != nil {
			return InvoiceDetail{}, ErrForbiddenParty
		}
		custID = party.ID
		custName = party.Name
	}
	if in.CustomerName != "" {
		custName = in.CustomerName
	}

	issueDate := orig.IssueDate.Time
	if in.IssueDate != "" {
		if t, err := time.Parse("2006-01-02", in.IssueDate); err == nil {
			issueDate = t
		}
	}
	dueDate := orig.DueDate.Time
	if in.DueDate != "" {
		if t, err := time.Parse("2006-01-02", in.DueDate); err == nil {
			dueDate = t
		}
	}

	subtotalMinor := orig.SubtotalMinor
	taxMinor := orig.TaxAmountMinor
	if in.TaxAmountMinor >= 0 {
		taxMinor = in.TaxAmountMinor
	}

	var savedItems []db.InvoiceItem
	if len(in.Items) > 0 {
		// Replace items
		_, err = qtx.DeleteInvoiceItemsByInvoiceID(ctx, db.DeleteInvoiceItemsByInvoiceIDParams{
			InvoiceID:   orig.ID,
			WorkspaceID: workspaceID,
		})
		if err != nil {
			return InvoiceDetail{}, err
		}

		subtotalMinor = 0
		for _, item := range in.Items {
			lineAmount := int64(item.Quantity) * item.UnitPriceMinor
			subtotalMinor += lineAmount
			rec, err := qtx.CreateInvoiceItem(ctx, db.CreateInvoiceItemParams{
				InvoiceID:      orig.ID,
				WorkspaceID:    workspaceID,
				Description:    item.Description,
				Quantity:       item.Quantity,
				UnitPriceMinor: item.UnitPriceMinor,
				AmountMinor:    lineAmount,
			})
			if err != nil {
				return InvoiceDetail{}, err
			}
			savedItems = append(savedItems, rec)
		}
	} else {
		savedItems, _ = qtx.ListInvoiceItemsByInvoiceID(ctx, db.ListInvoiceItemsByInvoiceIDParams{
			InvoiceID:   orig.ID,
			WorkspaceID: workspaceID,
		})
	}

	totalMinor := subtotalMinor + taxMinor

	updated, err := qtx.UpdateDraftInvoice(ctx, db.UpdateDraftInvoiceParams{
		ID:               orig.ID,
		WorkspaceID:      workspaceID,
		CustomerID:       custID,
		CustomerName:     custName,
		IssueDate:        pgtype.Date{Time: issueDate, Valid: true},
		DueDate:          pgtype.Date{Time: dueDate, Valid: true},
		SubtotalMinor:    subtotalMinor,
		TaxAmountMinor:   taxMinor,
		TotalAmountMinor: totalMinor,
		Notes:            optionalPgText(in.Notes),
		Terms:            optionalPgText(in.Terms),
	})
	if err != nil {
		return InvoiceDetail{}, fmt.Errorf("update draft invoice: %w", err)
	}

	if err := tx.Commit(ctx); err != nil {
		return InvoiceDetail{}, err
	}

	return InvoiceDetail{
		Invoice: updated,
		Items:   savedItems,
	}, nil
}

func (s *Service) FinalizeInvoice(ctx context.Context, workspaceID, userID, invoiceID int64) (InvoiceDetail, error) {
	orig, err := s.queries.GetInvoiceByID(ctx, db.GetInvoiceByIDParams{
		ID:          invoiceID,
		WorkspaceID: workspaceID,
	})
	if errors.Is(err, pgx.ErrNoRows) {
		return InvoiceDetail{}, ErrNotFound
	} else if err != nil {
		return InvoiceDetail{}, err
	}

	if orig.Status == "finalized" || orig.Status == "paid" || orig.Status == "partially_paid" {
		return InvoiceDetail{}, ErrAlreadyFinalized
	}
	if orig.Status == "voided" {
		return InvoiceDetail{}, ErrCannotFinalizeVoided
	}

	tx, err := s.pool.Begin(ctx)
	if err != nil {
		return InvoiceDetail{}, err
	}
	defer func() { _ = tx.Rollback(ctx) }()

	qtx := s.queries.WithTx(tx)

	finalized, err := qtx.FinalizeInvoice(ctx, db.FinalizeInvoiceParams{
		ID:          orig.ID,
		WorkspaceID: workspaceID,
	})
	if err != nil {
		return InvoiceDetail{}, fmt.Errorf("finalize invoice: %w", err)
	}

	// Post double-entry ledger entries!
	if err := s.postInvoiceLedger(ctx, qtx, workspaceID, finalized); err != nil {
		return InvoiceDetail{}, err
	}

	items, err := qtx.ListInvoiceItemsByInvoiceID(ctx, db.ListInvoiceItemsByInvoiceIDParams{
		InvoiceID:   finalized.ID,
		WorkspaceID: workspaceID,
	})
	if err != nil {
		return InvoiceDetail{}, err
	}

	if err := tx.Commit(ctx); err != nil {
		return InvoiceDetail{}, err
	}

	return InvoiceDetail{
		Invoice: finalized,
		Items:   items,
	}, nil
}

func (s *Service) postInvoiceLedger(ctx context.Context, qtx *db.Queries, workspaceID int64, inv db.Invoice) error {
	entry, err := qtx.CreateLedgerEntry(ctx, db.CreateLedgerEntryParams{
		WorkspaceID:      workspaceID,
		SourceType:       "sale",
		SourceID:         inv.ID,
		EntryDate:        inv.IssueDate,
		Currency:         inv.Currency,
		CurrencyExponent: inv.CurrencyExponent,
		Description:      pgtype.Text{String: "Invoice #" + inv.InvoiceNumber, Valid: true},
	})
	if err != nil {
		return fmt.Errorf("create invoice ledger entry: %w", err)
	}

	var lines []db.LedgerLine

	// Debit: Accounts Receivable (Asset) for total
	deb, err := qtx.CreateLedgerLine(ctx, db.CreateLedgerLineParams{
		LedgerEntryID: entry.ID,
		WorkspaceID:   workspaceID,
		AccountID:     pgtype.Int8{Valid: false},
		AccountClass:  "asset",
		DebitMinor:    inv.TotalAmountMinor,
		CreditMinor:   0,
		Description:   pgtype.Text{String: "Accounts Receivable: " + inv.CustomerName, Valid: true},
	})
	if err != nil {
		return err
	}
	lines = append(lines, deb)

	// Credit: Sales Revenue for subtotal
	credRevenue, err := qtx.CreateLedgerLine(ctx, db.CreateLedgerLineParams{
		LedgerEntryID: entry.ID,
		WorkspaceID:   workspaceID,
		AccountID:     pgtype.Int8{Valid: false},
		AccountClass:  "revenue",
		DebitMinor:    0,
		CreditMinor:   inv.SubtotalMinor,
		Description:   pgtype.Text{String: "Sales Revenue", Valid: true},
	})
	if err != nil {
		return err
	}
	lines = append(lines, credRevenue)

	// Credit: Output VAT for tax (if any)
	if inv.TaxAmountMinor > 0 {
		credTax, err := qtx.CreateLedgerLine(ctx, db.CreateLedgerLineParams{
			LedgerEntryID: entry.ID,
			WorkspaceID:   workspaceID,
			AccountID:     pgtype.Int8{Valid: false},
			AccountClass:  "liability",
			DebitMinor:    0,
			CreditMinor:   inv.TaxAmountMinor,
			Description:   pgtype.Text{String: "Output VAT Payable", Valid: true},
		})
		if err != nil {
			return err
		}
		lines = append(lines, credTax)
	}

	// Verify ledger balance
	var totalDebit, totalCredit int64
	for _, l := range lines {
		totalDebit += l.DebitMinor
		totalCredit += l.CreditMinor
	}
	if totalDebit != totalCredit || totalDebit != inv.TotalAmountMinor {
		return fmt.Errorf("%w: invoice debit %d != credit %d", ErrLedgerUnbalanced, totalDebit, totalCredit)
	}

	return nil
}

func (s *Service) VoidInvoice(ctx context.Context, workspaceID, userID, invoiceID int64, reason string) (InvoiceDetail, error) {
	reason = strings.TrimSpace(reason)
	if reason == "" {
		return InvoiceDetail{}, errors.New("void reason is required")
	}

	orig, err := s.queries.GetInvoiceByID(ctx, db.GetInvoiceByIDParams{
		ID:          invoiceID,
		WorkspaceID: workspaceID,
	})
	if errors.Is(err, pgx.ErrNoRows) {
		return InvoiceDetail{}, ErrNotFound
	} else if err != nil {
		return InvoiceDetail{}, err
	}

	if orig.Status == "voided" {
		return InvoiceDetail{}, ErrInvoiceAlreadyVoided
	}
	if orig.PaidAmountMinor > 0 {
		return InvoiceDetail{}, ErrCannotVoidPaidInvoice
	}

	tx, err := s.pool.Begin(ctx)
	if err != nil {
		return InvoiceDetail{}, err
	}
	defer func() { _ = tx.Rollback(ctx) }()

	qtx := s.queries.WithTx(tx)

	voided, err := qtx.VoidInvoice(ctx, db.VoidInvoiceParams{
		ID:          orig.ID,
		WorkspaceID: workspaceID,
		VoidReason:  pgtype.Text{String: reason, Valid: true},
	})
	if err != nil {
		return InvoiceDetail{}, fmt.Errorf("void invoice: %w", err)
	}

	// If was finalized, reverse the ledger entry!
	if orig.Status == "finalized" {
		revEntry, err := qtx.CreateLedgerEntry(ctx, db.CreateLedgerEntryParams{
			WorkspaceID:      workspaceID,
			SourceType:       "reversal",
			SourceID:         orig.ID,
			EntryDate:        pgtype.Date{Time: time.Now().UTC(), Valid: true},
			Currency:         orig.Currency,
			CurrencyExponent: orig.CurrencyExponent,
			Description:      pgtype.Text{String: "Void of invoice #" + orig.InvoiceNumber + ": " + reason, Valid: true},
		})
		if err != nil {
			return InvoiceDetail{}, err
		}

		// Reversal: Credit Accounts Receivable, Debit Revenue & VAT
		_, err = qtx.CreateLedgerLine(ctx, db.CreateLedgerLineParams{
			LedgerEntryID: revEntry.ID,
			WorkspaceID:   workspaceID,
			AccountID:     pgtype.Int8{Valid: false},
			AccountClass:  "revenue",
			DebitMinor:    orig.SubtotalMinor,
			CreditMinor:   0,
			Description:   pgtype.Text{String: "Reversal of Sales Revenue", Valid: true},
		})
		if err != nil {
			return InvoiceDetail{}, err
		}

		if orig.TaxAmountMinor > 0 {
			_, err = qtx.CreateLedgerLine(ctx, db.CreateLedgerLineParams{
				LedgerEntryID: revEntry.ID,
				WorkspaceID:   workspaceID,
				AccountID:     pgtype.Int8{Valid: false},
				AccountClass:  "liability",
				DebitMinor:    orig.TaxAmountMinor,
				CreditMinor:   0,
				Description:   pgtype.Text{String: "Reversal of Output VAT", Valid: true},
			})
			if err != nil {
				return InvoiceDetail{}, err
			}
		}

		_, err = qtx.CreateLedgerLine(ctx, db.CreateLedgerLineParams{
			LedgerEntryID: revEntry.ID,
			WorkspaceID:   workspaceID,
			AccountID:     pgtype.Int8{Valid: false},
			AccountClass:  "asset",
			DebitMinor:    0,
			CreditMinor:   orig.TotalAmountMinor,
			Description:   pgtype.Text{String: "Reversal of Accounts Receivable", Valid: true},
		})
		if err != nil {
			return InvoiceDetail{}, err
		}
	}

	items, err := qtx.ListInvoiceItemsByInvoiceID(ctx, db.ListInvoiceItemsByInvoiceIDParams{
		InvoiceID:   voided.ID,
		WorkspaceID: workspaceID,
	})
	if err != nil {
		return InvoiceDetail{}, err
	}

	if err := tx.Commit(ctx); err != nil {
		return InvoiceDetail{}, err
	}

	return InvoiceDetail{
		Invoice: voided,
		Items:   items,
	}, nil
}

func (s *Service) GetInvoice(ctx context.Context, workspaceID, invoiceID int64) (InvoiceDetail, error) {
	inv, err := s.queries.GetInvoiceByID(ctx, db.GetInvoiceByIDParams{
		ID:          invoiceID,
		WorkspaceID: workspaceID,
	})
	if errors.Is(err, pgx.ErrNoRows) {
		return InvoiceDetail{}, ErrNotFound
	} else if err != nil {
		return InvoiceDetail{}, err
	}

	items, err := s.queries.ListInvoiceItemsByInvoiceID(ctx, db.ListInvoiceItemsByInvoiceIDParams{
		InvoiceID:   inv.ID,
		WorkspaceID: workspaceID,
	})
	if err != nil {
		return InvoiceDetail{}, err
	}

	paymentsList, err := s.queries.ListPayments(ctx, db.ListPaymentsParams{
		WorkspaceID:      workspaceID,
		LinkedRecordType: pgtype.Text{String: "invoice", Valid: true},
		LinkedRecordID:   pgtype.Int8{Int64: invoiceID, Valid: true},
		Limit:            100,
	})
	if err != nil {
		return InvoiceDetail{}, err
	}

	var payments []PaymentDetail
	for _, p := range paymentsList {
		legs, _ := s.queries.ListPaymentLegsByPaymentID(ctx, db.ListPaymentLegsByPaymentIDParams{
			PaymentID:   p.ID,
			WorkspaceID: workspaceID,
		})
		payments = append(payments, PaymentDetail{
			Payment: p,
			Legs:    legs,
		})
	}

	return InvoiceDetail{
		Invoice:  inv,
		Items:    items,
		Payments: payments,
	}, nil
}

type ListInvoicesFilter struct {
	Search     string `form:"search"`
	FromDate   string `form:"from"`
	ToDate     string `form:"to"`
	Status     string `form:"status"`
	CustomerID int64  `form:"customer_id"`
	BeforeID   int64  `form:"before_id"`
	Limit      int32  `form:"limit"`
}

func (s *Service) ListInvoices(ctx context.Context, workspaceID int64, f ListInvoicesFilter) ([]db.Invoice, error) {
	limit := f.Limit
	if limit <= 0 || limit > 100 {
		limit = 50
	}

	var fromDateParam, toDateParam pgtype.Date
	if f.FromDate != "" {
		if t, err := time.Parse("2006-01-02", f.FromDate); err == nil {
			fromDateParam = pgtype.Date{Time: t, Valid: true}
		}
	}
	if f.ToDate != "" {
		if t, err := time.Parse("2006-01-02", f.ToDate); err == nil {
			toDateParam = pgtype.Date{Time: t, Valid: true}
		}
	}

	var statusParam pgtype.Text
	if f.Status != "" {
		statusParam = pgtype.Text{String: f.Status, Valid: true}
	}

	var custIDParam pgtype.Int8
	if f.CustomerID > 0 {
		custIDParam = pgtype.Int8{Int64: f.CustomerID, Valid: true}
	}

	var beforeIDParam pgtype.Int8
	if f.BeforeID > 0 {
		beforeIDParam = pgtype.Int8{Int64: f.BeforeID, Valid: true}
	}

	return s.queries.ListInvoices(ctx, db.ListInvoicesParams{
		Search:      searchParam(f.Search),
		WorkspaceID: workspaceID,
		Limit:       limit,
		FromDate:    fromDateParam,
		ToDate:      toDateParam,
		Status:      statusParam,
		CustomerID:  custIDParam,
		BeforeID:    beforeIDParam,
	})
}

// ---------------- Customer Deposits and Wallets ----------------

type CustomerWalletDepositInput struct {
	AmountMinor    int64  `json:"amount_minor"`
	AmountMajor    string `json:"amount"` // optional
	Currency       string `json:"currency"`
	MoneyAccountID int64  `json:"money_account_id" binding:"required"`
	Notes          string `json:"notes"`
	Reference      string `json:"reference"`
	IdempotencyKey string `json:"idempotency_key"`
}

type WalletDepositResult struct {
	Wallet      db.CustomerWallet    `json:"wallet"`
	Transaction db.WalletTransaction `json:"transaction"`
	Ledger      *db.LedgerEntry      `json:"ledger_entry,omitempty"`
}

func (s *Service) DepositToCustomerWallet(ctx context.Context, workspaceID, userID, customerID int64, in CustomerWalletDepositInput) (WalletDepositResult, error) {
	party, err := s.queries.GetCounterpartyByID(ctx, db.GetCounterpartyByIDParams{
		ID:          customerID,
		WorkspaceID: workspaceID,
	})
	if err != nil {
		return WalletDepositResult{}, ErrForbiddenParty
	}

	currency := strings.ToUpper(strings.TrimSpace(in.Currency))
	if currency == "" {
		currency = "NGN"
	}
	exponent := CurrencyExponent(currency)

	amountMinor := in.AmountMinor
	if in.AmountMajor != "" {
		parsed, err := ParseMajorToMinor(in.AmountMajor, exponent)
		if err != nil {
			return WalletDepositResult{}, err
		}
		amountMinor = parsed
	}
	if amountMinor <= 0 {
		return WalletDepositResult{}, ErrNegativeAmount
	}

	acc, err := s.queries.GetMoneyAccountByID(ctx, db.GetMoneyAccountByIDParams{
		ID:          in.MoneyAccountID,
		WorkspaceID: workspaceID,
	})
	if err != nil {
		return WalletDepositResult{}, ErrForbiddenAccount
	}

	tx, err := s.pool.Begin(ctx)
	if err != nil {
		return WalletDepositResult{}, err
	}
	defer func() { _ = tx.Rollback(ctx) }()

	qtx := s.queries.WithTx(tx)

	// Ensure wallet row exists
	if _, err := qtx.GetOrCreateCustomerWallet(ctx, db.GetOrCreateCustomerWalletParams{
		WorkspaceID:      workspaceID,
		CustomerID:       customerID,
		Currency:         currency,
		CurrencyExponent: int32(exponent),
	}); err != nil {
		return WalletDepositResult{}, fmt.Errorf("get or create wallet: %w", err)
	}

	// Update wallet balance (+ amount)
	updatedWallet, err := qtx.UpdateCustomerWalletBalance(ctx, db.UpdateCustomerWalletBalanceParams{
		WorkspaceID:  workspaceID,
		CustomerID:   customerID,
		Currency:     currency,
		BalanceMinor: amountMinor,
	})
	if err != nil {
		return WalletDepositResult{}, fmt.Errorf("update wallet balance: %w", err)
	}

	// Update money account balance (+ amount)
	_, err = qtx.UpdateMoneyAccountBalance(ctx, db.UpdateMoneyAccountBalanceParams{
		ID:                  acc.ID,
		WorkspaceID:         workspaceID,
		CurrentBalanceMinor: amountMinor,
	})
	if err != nil {
		return WalletDepositResult{}, fmt.Errorf("update money account balance: %w", err)
	}

	var idempParam pgtype.Text
	if strings.TrimSpace(in.IdempotencyKey) != "" {
		idempParam = pgtype.Text{String: strings.TrimSpace(in.IdempotencyKey), Valid: true}
	}

	// Record wallet transaction
	wTxn, err := qtx.CreateWalletTransaction(ctx, db.CreateWalletTransactionParams{
		WorkspaceID:       workspaceID,
		CustomerID:        customerID,
		TransactionType:   "deposit",
		AmountMinor:       amountMinor,
		BalanceAfterMinor: updatedWallet.BalanceMinor,
		MoneyAccountID:    pgtype.Int8{Int64: acc.ID, Valid: true},
		InvoiceID:         pgtype.Int8{Valid: false},
		Notes:             optionalPgText(in.Notes),
		Reference:         optionalPgText(in.Reference),
		IdempotencyKey:    idempParam,
		CreatedByUserID:   pgtype.Int8{Int64: userID, Valid: true},
	})
	if err != nil {
		return WalletDepositResult{}, fmt.Errorf("record wallet transaction: %w", err)
	}

	// Create balanced double-entry ledger entry:
	// Debit: Bank / Cash (Asset)
	// Credit: Customer Deposit Liability (Liability)
	entry, err := qtx.CreateLedgerEntry(ctx, db.CreateLedgerEntryParams{
		WorkspaceID:      workspaceID,
		SourceType:       "deposit",
		SourceID:         wTxn.ID,
		EntryDate:        pgtype.Date{Time: time.Now().UTC(), Valid: true},
		Currency:         currency,
		CurrencyExponent: int32(exponent),
		Description:      pgtype.Text{String: "Customer deposit from " + party.Name, Valid: true},
	})
	if err != nil {
		return WalletDepositResult{}, err
	}

	_, err = qtx.CreateLedgerLine(ctx, db.CreateLedgerLineParams{
		LedgerEntryID: entry.ID,
		WorkspaceID:   workspaceID,
		AccountID:     pgtype.Int8{Int64: acc.ID, Valid: true},
		AccountClass:  "asset",
		DebitMinor:    amountMinor,
		CreditMinor:   0,
		Description:   pgtype.Text{String: "Deposit into " + acc.Name, Valid: true},
	})
	if err != nil {
		return WalletDepositResult{}, err
	}

	_, err = qtx.CreateLedgerLine(ctx, db.CreateLedgerLineParams{
		LedgerEntryID: entry.ID,
		WorkspaceID:   workspaceID,
		AccountID:     pgtype.Int8{Valid: false},
		AccountClass:  "liability",
		DebitMinor:    0,
		CreditMinor:   amountMinor,
		Description:   pgtype.Text{String: "Customer Deposit Liability: " + party.Name, Valid: true},
	})
	if err != nil {
		return WalletDepositResult{}, err
	}

	if err := tx.Commit(ctx); err != nil {
		return WalletDepositResult{}, err
	}

	return WalletDepositResult{
		Wallet:      updatedWallet,
		Transaction: wTxn,
		Ledger:      &entry,
	}, nil
}

